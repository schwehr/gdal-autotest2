using ::testing::TestWithParam;

TEST(CplIsASCIITest, Basic) { ASSERT_TRUE(CPLIsASCII("abcABC", 6)); }

TEST(CplIsASCIITest, NonAsciiCharacter) { ASSERT_FALSE(CPLIsASCII("\xff", 1)); }

TEST(CplIsASCIITest, UseProvidedStringLength) {
  // When the provided string length is -1, then the length of the provided
  // string should be used
  ASSERT_TRUE(CPLIsASCII("abcABC", static_cast<size_t>(-1)));
}

TEST(CplIsASCIITest, LengthProvidedIsRespected) {
  ASSERT_TRUE(CPLIsASCII("abcABC\xff", 6));
}

struct CplRecodeTestCase {
  const char* input;
  const char* input_encoding;
  const char* expected;
  bool expect_warning;
};

using CplRecodeTest = TestWithParam<CplRecodeTestCase>;

TEST_P(CplRecodeTest, RecodingToUtf8) {
  WithQuietHandler silence_warnings;
  const CplRecodeTestCase& tc = GetParam();

  CPLErrorReset();
  CPLClearRecodeWarningFlags();

  char* output = CPLRecode(tc.input, tc.input_encoding, CPL_ENC_UTF8);
  absl::Cleanup cleanup = [output] { CPLFree(output); };

  if (tc.expect_warning) {
    std::string expected_warning = absl::Substitute(
        "Recode from $0 to UTF-8 not supported, treated as ISO-8859-1 to "
        "UTF-8.",
        tc.input_encoding);
    EXPECT_STREQ(expected_warning.c_str(), CPLGetLastErrorMsg());
    EXPECT_EQ(CPLE_AppDefined, CPLGetLastErrorNo());
    EXPECT_EQ(CE_Warning, CPLGetLastErrorType());
  } else {
    EXPECT_STREQ("", CPLGetLastErrorMsg());
    EXPECT_EQ(CPLE_None, CPLGetLastErrorNo());
    EXPECT_EQ(CE_None, CPLGetLastErrorType());
  }

  EXPECT_STREQ(tc.expected, output);
}

